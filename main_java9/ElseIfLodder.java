package main_java9;

public class ElseIfLodder {
    public static void main(String[] args) {
        int marks = 85;
        if(marks>=90){
            System.out.println("Grade A ");
        }else if(marks >= 80){
            System.out.println("Grade B ");
        }else{
            System.out.println("Grade C ");
        }
    }
}
// output Grade B